class Product(Base):
    """Catalog product entity."""
    __tablename__ = "products"

    product_id = Column(String(64), primary_key=True, index=True)
    product_name = Column(String(255), nullable=False, index=True)
    category = Column(String(100), nullable=False, index=True)
    current_stock = Column(Integer, nullable=False, default=0)
    low_stock_threshold = Column(Integer, nullable=False, default=10)
    unit_price = Column(Float, nullable=False, default=0.0)
    supplier_lead_time_days = Column(Integer, nullable=False, default=3)
    reorder_quantity = Column(Integer, nullable=False, default=20)
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    sales_logs = relationship("SalesLog", back_populates="product", cascade="all, delete-orphan")


class SalesLog(Base):
    """Historical sales transactional log."""
    __tablename__ = "sales_logs"

    id = Column(Integer, primary_key=True, autoincrement=True)
    product_id = Column(String(64), ForeignKey("products.product_id"), nullable=False, index=True)
    date = Column(String(32), nullable=False, index=True)
    units_sold = Column(Integer, nullable=False, default=0)
    price = Column(Float, nullable=True, default=0.0)
    channel = Column(String(50), default="POS_STORE")
    promotion_applied = Column(Boolean, default=False)
    discount_percent = Column(Float, default=0.0)
    created_at = Column(DateTime, default=datetime.utcnow)

    product = relationship("Product", back_populates="sales_logs")


