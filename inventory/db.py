def _create_db_engine():
    global DATABASE_URL
    urls_to_try = []

    unpooled = os.getenv("DATABASE_URL_UNPOOLED")
    pooled = os.getenv("DATABASE_URL")

    if unpooled:
        urls_to_try.append(unpooled)
    if pooled and pooled != unpooled:
        urls_to_try.append(pooled)

    for raw_url in urls_to_try:
        url = raw_url
        if url.startswith("postgresql://"):
            url = url.replace("postgresql://", "postgresql+psycopg2://", 1)
        try:
            eng = create_engine(url, pool_pre_ping=True, pool_recycle=300, connect_args={"connect_timeout": 5})
            from sqlalchemy import text
            with eng.connect() as conn:
                conn.execute(text("SELECT 1"))
            DATABASE_URL = url
            return eng
        except Exception as err:
            print(f"[inventory/db] PostgreSQL connection notice: {err}. Trying fallback...")
            continue

    # Fallback to local SQLite if remote PostgreSQL is unreachable
    sqlite_dir = _HERE / "inventory" / "data"
    sqlite_dir.mkdir(parents=True, exist_ok=True)
    sqlite_path = sqlite_dir / "advantage.db"
    DATABASE_URL = f"sqlite:///{sqlite_path}"
    print(f"[inventory/db] Operating with local database at {sqlite_path}")
    return create_engine(DATABASE_URL, pool_pre_ping=True, connect_args={"check_same_thread": False})


engine = _create_db_engine()
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)
Base = declarative_base()


