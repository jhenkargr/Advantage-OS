def get_db() -> Generator:
    """FastAPI Dependency for database sessions."""
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()


_INITIALIZED_ENGINES = set()


def ensure_tables(target_engine=None):
    """Ensures all tables and schema columns exist in target engine."""
    eng = target_engine or engine
    eng_key = str(getattr(eng, "url", id(eng)))
    if eng_key in _INITIALIZED_ENGINES:
        return

    Base.metadata.create_all(bind=eng)
    try:
        from sqlalchemy import text
        dialect_name = eng.dialect.name
        with eng.connect() as conn:
            if dialect_name == "sqlite":
                res = conn.execute(text("PRAGMA table_info(sales_logs)")).fetchall()
                col_names = [r[1] for r in res]
                if "price" not in col_names:
                    conn.execute(text("ALTER TABLE sales_logs ADD COLUMN price FLOAT DEFAULT 0.0"))
                    conn.commit()
            else:
                conn.execute(text("ALTER TABLE sales_logs ADD COLUMN IF NOT EXISTS price DOUBLE PRECISION DEFAULT 0.0"))
                conn.commit()
    except Exception as exc:
        print(f"[inventory/db] Notice during column check: {exc}")

    _INITIALIZED_ENGINES.add(eng_key)


def init_db():
    """Create all tables in Neon PostgreSQL and ensure schema migrations."""
    ensure_tables(engine)
    print("✅ Neon PostgreSQL database schema successfully created / verified.")


def save_stock_plan_to_db(df: pd.DataFrame, db: Session = None) -> int:
    """Save or update stock plan rows into the database stock_plans table."""
    close_session = False
    if db is None:
        db = SessionLocal()
        close_session = True

    try:
        ensure_tables(db.get_bind())
        # Clear existing stock plans
        db.query(StockPlan).delete()
        records = []
        for _, row in df.iterrows():
            def _clean_int(val):
                if pd.isna(val) or val is None or str(val).lower() in ("nan", "<na>", "none", "n/a"):
                    return None
                try:
                    return int(float(val))
                except (ValueError, TypeError):
                    return None

            def _clean_float(val):
                if pd.isna(val) or val is None or str(val).lower() in ("nan", "<na>", "none", "n/a"):
                    return 0.0
                try:
                    return float(val)
                except (ValueError, TypeError):
                    return 0.0

            pid = str(row.get("Product ID", row.get("product_id", ""))).strip()
            pname = str(row.get("Product", row.get("product_name", pid))).strip()
            records.append(
                StockPlan(
                    product_id=pid,
                    product_name=pname,
                    avg_daily_demand=_clean_float(row.get("Avg daily demand", row.get("avg_daily_demand", 0.0))),
                    forecast_30d=_clean_float(row.get("30-day forecast", row.get("forecast_30d", 0.0))),
                    current_stock=str(row.get("Current stock", row.get("current_stock", "0"))).strip(),
                    safety_stock=_clean_int(row.get("Safety stock", row.get("safety_stock"))),
                    reorder_point=_clean_int(row.get("Reorder point", row.get("reorder_point"))),
                    target_stock=_clean_int(row.get("Target stock", row.get("target_stock"))),
                    order_qty_now=_clean_int(row.get("Order qty now", row.get("order_qty_now"))),
                    status=str(row.get("Status", row.get("status", "OK"))),
                    note=str(row.get("Note", row.get("note", ""))) if pd.notna(row.get("Note", row.get("note"))) else None,
                )
            )
        if records:
            db.bulk_save_objects(records)
            db.commit()
        return len(records)
    except Exception as exc:
        db.rollback()
        raise exc
    finally:
        if close_session:
            db.close()


def seed_data_from_csv():
    """Migrate catalog CSV, sales log CSV, and stock plan CSV into Neon PostgreSQL."""
    from inventory.config import CATALOG_PATH, SALES_LOG_PATH

    db = SessionLocal()
    try:
        # 1. Seed Product Catalog
        if CATALOG_PATH.exists():
            df_cat = pd.read_csv(CATALOG_PATH)
            for _, row in df_cat.iterrows():
                pid = str(row["product_id"]).strip()
                existing = db.query(Product).filter(Product.product_id == pid).first()
                if not existing:
                    prod = Product(
                        product_id=pid,
                        product_name=str(row.get("product_name", pid)),
                        category=str(row.get("category", "General")),
                        current_stock=int(row.get("current_stock", 0)),
                        low_stock_threshold=int(row.get("low_stock_threshold", 10)),
                        unit_price=float(row.get("unit_price", 0.0)),
                        supplier_lead_time_days=int(row.get("supplier_lead_time_days", 3)),
                        reorder_quantity=int(row.get("reorder_quantity", 20)),
                    )
                    db.add(prod)
            db.commit()
            print(f"📦 Seeded/Verified {len(df_cat)} products into Neon PostgreSQL.")

        # 2. Seed Sales Logs (if empty)
        if SALES_LOG_PATH.exists() and db.query(SalesLog).count() == 0:
            df_sales = pd.read_csv(SALES_LOG_PATH)
            sales_records = []
            for _, row in df_sales.iterrows():
                sales_records.append(
                    SalesLog(
                        product_id=str(row.get("product_id", "")).strip(),
                        date=str(row.get("date", datetime.utcnow().strftime("%Y-%m-%d"))),
                        units_sold=int(row.get("units_sold", 0)),
                        channel=str(row.get("channel", "POS_STORE")),
                        promotion_applied=bool(row.get("promotion_applied", False)),
                        discount_percent=float(row.get("discount_percent", 0.0)),
                    )
                )
            if sales_records:
                db.bulk_save_objects(sales_records)
                db.commit()
                print(f"📊 Seeded {len(sales_records)} historical sales log records into Neon PostgreSQL.")

        # 3. Seed Influencer Clusters (if empty)
        inf_csv_candidates = [
            _HERE / "influencer_clusters.csv",
            _HERE.parent / "influencer_clusters.csv",
            Path("influencer_clusters.csv"),
            _HERE / "youtube_influencer_data (1).csv",
            _HERE.parent / "youtube_influencer_data (1).csv",
        ]
        inf_path = next((p for p in inf_csv_candidates if p.is_file()), None)
        if inf_path and db.query(Influencer).count() == 0:
            df_inf = pd.read_csv(inf_path)
            inf_records = []
            for _, row in df_inf.iterrows():
                cid = str(row.get("channel_id", "")).strip()
                if not cid or cid.lower() == "nan":
                    continue
                inf_records.append(
                    Influencer(
                        channel_id=cid,
                        channel_name=str(row.get("channel_name", cid)),
                        description=str(row.get("description", "")) if pd.notna(row.get("description")) else None,
                        country=str(row.get("country", "")) if pd.notna(row.get("country")) else None,
                        published_at=str(row.get("published_at", "")) if pd.notna(row.get("published_at")) else None,
                        subscriber_count=int(row.get("subscriber_count", 0)) if pd.notna(row.get("subscriber_count")) else 0,
                        video_count=int(row.get("video_count", 0)) if pd.notna(row.get("video_count")) else 0,
                        total_view_count=int(row.get("total_view_count", 0)) if pd.notna(row.get("total_view_count")) else 0,
                        avg_views_per_video=float(row.get("avg_views_per_video", 0.0)) if pd.notna(row.get("avg_views_per_video")) else 0.0,
                        keywords=str(row.get("keywords", "")) if pd.notna(row.get("keywords")) else None,
                        clean_description=str(row.get("clean_description", "")) if pd.notna(row.get("clean_description")) else None,
                        clean_keywords=str(row.get("clean_keywords", "")) if pd.notna(row.get("clean_keywords")) else None,
                        engagement_score=float(row.get("engagement_score", 0.0)) if pd.notna(row.get("engagement_score")) else 0.0,
                        influencer_tier=str(row.get("influencer_tier", "")) if pd.notna(row.get("influencer_tier")) else None,
                        bot_flag=bool(row.get("bot_flag", False)) if pd.notna(row.get("bot_flag")) else False,
                        cluster_id=int(row.get("cluster_id", 0)) if pd.notna(row.get("cluster_id")) else None,
                        cluster_label=str(row.get("cluster_label", "")) if pd.notna(row.get("cluster_label")) else None,
                    )
                )
            if inf_records:
                db.bulk_save_objects(inf_records)
                db.commit()
                print(f"🌟 Seeded {len(inf_records)} influencers from '{inf_path.name}' into Neon PostgreSQL.")

        # 4. Seed Stock Plan (if empty)
        sp_candidates = [
            _HERE.parent / "stock_plan.csv",
            _HERE / "stock_plan.csv",
            Path("stock_plan.csv"),
        ]
        sp_path = next((p for p in sp_candidates if p.is_file()), None)
        if sp_path and db.query(StockPlan).count() == 0:
            df_sp = pd.read_csv(sp_path)
            saved_count = save_stock_plan_to_db(df_sp, db=db)
            print(f"📈 Seeded {saved_count} stock plan records from '{sp_path.name}' into Neon PostgreSQL.")

    except Exception as e:
        db.rollback()
        print(f"⚠️ Error during database seeding: {e}")
    finally:
        db.close()


def save_ml_model_to_db(
    model_name: str,
    model_bytes: bytes,
    filename: str = "model_test_analysis.pkl",
    meta_info: dict = None,
    db: Session = None,
) -> MLModel:
    """Saves or updates an ML model binary artifact in the database."""
    close_session = False
    if db is None:
        db = SessionLocal()
        close_session = True
    try:
        ensure_tables(db.get_bind() if hasattr(db, "get_bind") else None)
        record = db.query(MLModel).filter(MLModel.model_name == model_name).first()
        meta_str = json.dumps(meta_info) if meta_info else None
        if not record:
            record = MLModel(
                model_name=model_name,
                version="v1",
                filename=filename,
                model_binary=model_bytes,
                file_size_bytes=len(model_bytes),
                meta_info=meta_str,
            )
            db.add(record)
        else:
            record.filename = filename
            record.model_binary = model_bytes
            record.file_size_bytes = len(model_bytes)
            record.meta_info = meta_str
            record.updated_at = datetime.utcnow()
        db.commit()
        db.refresh(record)
        return record
    finally:
        if close_session:
            db.close()


def get_ml_model_from_db(model_name: str, db: Session = None) -> Optional[MLModel]:
    """Retrieves an ML model binary record from the database."""
    close_session = False
    if db is None:
        db = SessionLocal()
        close_session = True
    try:
        ensure_tables(db.get_bind() if hasattr(db, "get_bind") else None)
        return db.query(MLModel).filter(MLModel.model_name == model_name).first()
    finally:
        if close_session:
            db.close()


